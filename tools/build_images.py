# Social-share cards (1200x630). art = (source, mode) where mode is 'contain' (art on the right)
# or 'cover' (picture fills the right side and fades into the dark panel).
OG = {
    'og/my-lost-parts.jpg':    ('My Lost Parts',    'Physics puzzle game', '#7cc4ff', 'my Lost Parts/Goro.png', 'contain'),
    'og/insectmen-jungle.jpg': ('Insectmen Jungle', 'Action game',         '#9bd35a', 'Insectmen Jungle/loading StartScreen.png', 'cover'),
}

BG = (13, 20, 26)
INK = (244, 244, 235)
MUTED = (182, 197, 197)
LIME = (215, 241, 113)
FONT = '/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf'


def has_alpha(im):
    if im.mode in ('RGBA', 'LA') or (im.mode == 'P' and 'transparency' in im.info):
        return im.convert('RGBA').getextrema()[3][0] < 255
    return False


def load(src):
    im = Image.open(SRC / src)
    im.load()
    return im.convert('RGBA') if has_alpha(im) else im.convert('RGB')


def build_image(out, src, w, h, opts=None):
    opts = opts or {}
    im = load(src)
    if 'background' in opts and im.mode == 'RGBA':
        flat = Image.new('RGBA', im.size, opts['background'])
        flat.alpha_composite(im)
        im = flat.convert('RGB')
    im.thumbnail((w, h), Image.LANCZOS)
    dest = OUT / out
    dest.parent.mkdir(parents=True, exist_ok=True)
    im.save(dest, 'WEBP', quality=opts.get('quality', 82), method=6)
    return im.size, dest.stat().st_size


def build_og(out, title, sub, accent, src, mode):
    W, H = 1200, 630
    card = Image.new('RGB', (W, H), BG)
    art = load(src)
    if mode == 'contain':
        art.thumbnail((520, 470), Image.LANCZOS)
        a = art.convert('RGBA')
        card.paste(a, (880 - a.width // 2, (H - a.height) // 2), a)
    else:
        a = art.convert('RGB')
        scale = max(640 / a.width, H / a.height)
        a = a.resize((round(a.width * scale), round(a.height * scale)), Image.LANCZOS)
        a = a.crop(((a.width - 640) // 2, (a.height - H) // 2, (a.width - 640) // 2 + 640, (a.height - H) // 2 + H))
        mask = Image.new('L', (640, H), 255)
        md = ImageDraw.Draw(mask)
        for x in range(160):
            md.line([(x, 0), (x, H)], fill=round(255 * x / 160))
        card.paste(a, (W - 640, 0), mask)
    d = ImageDraw.Draw(card)
    d.rounded_rectangle((64, 70, 112, 118), 10, fill=LIME)
    d.text((88, 94), 'B', font=ImageFont.truetype(FONT, 30), fill=(19, 34, 3), anchor='mm')
    d.text((126, 94), 'BEHARSOFT', font=ImageFont.truetype(FONT, 28), fill=INK, anchor='lm')
    size = 64
    while ImageFont.truetype(FONT, size).getlength(title) > 560 and size > 40:
        size -= 2
    d.text((64, 288), title, font=ImageFont.truetype(FONT, size), fill=INK, anchor='lm')
    d.rectangle((64, 350, 124, 356), fill=accent)
    d.text((64, 396), sub, font=ImageFont.truetype(FONT, 28), fill=MUTED, anchor='lm')
    dest = OUT / out
    card.save(dest, 'JPEG', quality=86, optimize=True, progressive=True)
    return (W, H), dest.stat().st_size


def main():
    only = sys.argv[1] if len(sys.argv) > 1 else ''
    missing = [v[0] for v in IMAGES.values() if not (SRC / v[0]).exists()]
    missing += [v[3] for v in OG.values() if not (SRC / v[3]).exists()]
    if missing:
        sys.exit('Missing originals in images/:\n  ' + '\n  '.join(missing))
    for out, spec in IMAGES.items():
        if only in out:
            size, b = build_image(out, *spec)
            print(f'{out:38s} {size[0]:>4}x{size[1]:<4} {b // 1024:>4} KB')
    for out, args in OG.items():
        if only in out:
            size, b = build_og(out, *args)
            print(f'{out:38s} {size[0]:>4}x{size[1]:<4} {b // 1024:>4} KB')


if __name__ == '__main__':
    main()
